    public function getRandomImages($folderPath, $count = 5)
    {
        $fullPath = public_path($folderPath);

        if (!File::exists($fullPath)) {
            return [];
        }

        $allFiles = collect(File::files($fullPath))
            ->filter(function ($file) {
                return in_array($file->getExtension(), ['jpg', 'jpeg', 'png', 'webp']);
            })
            ->shuffle()
            ->take($count)
            ->map(function ($file) use ($folderPath) {
                return $folderPath . '/' . $file->getFilename();
            })
            ->values()
            ->toArray();

        return $allFiles;
    }

    public function getRandomRegles($count = 4)
    {
        $shuffledRegles = collect($this->reglesOptions)->shuffle()->take($count);
        return json_encode($shuffledRegles->values()->toArray());
    }

